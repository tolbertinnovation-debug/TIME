// Builds assets/learning/workspace.css for the account workspace (sign-in, student, lecturer and
// admin screens) from the original portal.css: every rule is scoped to #workspace so it sits
// inside the main site's page shell, and the site-level parts (old header, sidebar, footer,
// fonts, page body) are dropped. `node scripts/workspace-css.mjs` rewrites the file.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './layout.mjs';

const SRC = join(ROOT, 'assets/learning/portal.css');
const OUT = join(ROOT, 'assets/learning/workspace.css');
const DROP = /^(:root|\*|body|html|main|main:focus|\.skip|\.skip:focus|\.top|\.top>.*|\.brand.*|\.site-link|\.shell.*|\.sidebar.*|\.cohort-tag.*|\.blend.*|\.footer|\.sidebar-title.*|\.sidebar-bottom.*)$/;
const OUTSIDE = /^(#toast|\.request-indicator.*|\.request-spinner.*|\.sr-only|@?\d+%|from|to)$/;

function scope(selectors) {
  const kept = selectors.split(',').map((s) => s.trim()).filter((s) => s && !DROP.test(s));
  return kept.map((s) => (OUTSIDE.test(s) || /^\d+%$/.test(s) ? s : `#workspace ${s}`)).join(',');
}

// Minimal parser for the flat, minified stylesheet: rules, @media blocks, @keyframes and @font-face.
function walk(css) {
  let out = '', i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) break;
    const head = css.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (depth && j < css.length) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    const body = css.slice(open + 1, j - 1);
    if (head.startsWith('@font-face')) { /* the site already loads these fonts */ }
    else if (head.startsWith('@keyframes')) out += `${head}{${body}}`;
    else if (head.startsWith('@media')) { const inner = walk(body); if (inner) out += `${head}{${inner}}`; }
    else { const sel = scope(head); if (sel) out += `${sel}{${body}}`; }
    i = j;
  }
  return out;
}

const css = readFileSync(SRC, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const vars = '#workspace{--green:var(--olive-deep);--pale:var(--olive-soft);--gold:#dfbb65;--radius:18px}';
writeFileSync(OUT, `/* Generated by scripts/workspace-css.mjs from portal.css. Do not edit by hand; edit workspace-theme.css. */\n${vars}${walk(css)}\n`);
console.log('workspace.css written');
