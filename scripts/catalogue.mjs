// The TIME Inc. catalogue as Schools → Programs → Courses (docs/online-learning-blueprint.md §1).
// Course facts come from data/programs.json; this script adds each course's school and planned
// delivery mode, writes data/catalogue.json, and renders the "Browse by school" section of
// programs.html and the course options of the online application form on admissions.html.
// `npm run catalogue` updates the files; the tests fail when they are out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT } from './layout.mjs';
import { DATA as PROGRAMS } from './programs.mjs';

export const SCHOOLS = [
  { id: 'teacher-education', title: 'School of Teacher Education', short: 'Teacher Education', icon: 'M22 10 12 5 2 10l10 5 10-5z|M6 12v5c3 2 9 2 12 0v-5',
    blurb: 'Accredited teacher certificates, science lab training and the skills that make a good school run well.' },
  { id: 'health-community', title: 'School of Health, Community & Environment', short: 'Health, Community & Environment', icon: 'M12 21s-7-4.4-9.3-9A5.2 5.2 0 0 1 12 6a5.2 5.2 0 0 1 9.3 6c-2.3 4.6-9.3 9-9.3 9Z',
    blurb: 'Community health, safety, counselling and environmental courses for health and community workers.' },
  { id: 'business-media', title: 'School of Business, Leadership & Media', short: 'Business, Leadership & Media', icon: 'M3 7h18v13H3z|M8 7V4h8v3',
    blurb: 'Accounting, monitoring and evaluation, project management, journalism and professional practice.' },
  { id: 'ministry', title: 'School of Ministry', short: 'Ministry', icon: 'M12 2v20|M5 8h14',
    blurb: 'Biblical interpretation and church leadership for pastors and ministry workers.' },
];

// School for every course, by program and course name (blueprint §1.2).
const SCHOOL_OF = {
  'c-certificate': () => 'teacher-education',
  'science-lab': () => 'teacher-education',
  skills: () => 'teacher-education',
  professional: (name) => /Professional Ethics/.test(name) ? 'business-media' : 'health-community',
  diploma: (name) => /Phonics|School Leadership|School Finance/.test(name) ? 'teacher-education'
    : /Biblical|Church/.test(name) ? 'ministry' : 'business-media',
  'special-education': (name) => /Drug|Health Care/.test(name) ? 'health-community'
    : /Project Planning/.test(name) ? 'business-media' : 'teacher-education',
};

// Delivery modes (blueprint §1.3). Only Special Education's blended format is in place today;
// the rest are TIME's proposals until leadership confirms them.
function delivery(program, name) {
  if (program === 'special-education') return { mode: 'blended', confirmed: true };
  if (program === 'science-lab') return { mode: 'on-campus', confirmed: false };
  if (/QuickBooks|Monitoring|Research Skills|Professional Ethics|Journalism|Greek/.test(name)) return { mode: 'online', confirmed: false };
  return { mode: 'blended', confirmed: false };
}
export const MODES = {
  'on-campus': { label: 'On campus', text: 'Classes at the Margibi campus, with materials posted online.' },
  blended: { label: 'Blended', text: 'Weekly online lessons plus in-person sessions with your lecturer.' },
  online: { label: 'Online', text: 'Fully online, with live sessions and an online final assessment.' },
};

const slug = (s) => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const plain = (s) => String(s).replace(/"/g, '“').replace(/“([^“]*)“/g, '“$1”');

export function catalogue() {
  const courses = [];
  for (const p of PROGRAMS) {
    for (const c of p.courses) {
      const name = c.detail ? `${c.name} (${c.detail})` : c.name;
      const d = delivery(p.slug, c.name);
      courses.push({
        id: `${p.slug}--${slug(c.name)}`, title: name, school_id: SCHOOL_OF[p.slug](c.name), program_id: p.slug,
        program: plain(p.name), program_page: p.file, lecturer: c.lecturer || null,
        duration: p.slug === 'c-certificate' ? '9 months' : p.slug === 'science-lab' ? '10 weeks + 2-month internship' : '10 weeks',
        tuition_usd: p.tuition ?? null, installments: p.installments ? 2 : null,
        delivery_mode: d.mode, delivery_confirmed: d.confirmed,
        next_cohorts: [
          { register_by: '2027-01-04', start_date: '2027-03-08', tracks: ['weekday', 'saturday'] },
          { register_by: null, start_date: '2027-10-14', tracks: ['weekday', 'saturday'] },
        ],
      });
    }
  }
  const schools = SCHOOLS.map(({ icon, ...s }) => ({ ...s, programs: [...new Set(courses.filter((c) => c.school_id === s.id).map((c) => c.program_id))] }));
  return { version: 1, note: 'Generated by scripts/catalogue.mjs. Delivery modes marked delivery_confirmed: false are TIME proposals awaiting confirmation.', schools, courses };
}

const svg = (paths, size = 26) => `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${paths.split('|').map((d) => `<path d="${d}"/>`).join('')}</svg>`;

export function schoolsSection(cat) {
  const cards = SCHOOLS.map((s) => {
    const list = cat.courses.filter((c) => c.school_id === s.id);
    const programs = [...new Set(list.map((c) => c.program_id))].map((id) => PROGRAMS.find((p) => p.slug === id));
    return `
          <article class="school-card reveal" id="school-${s.id}">
            <div class="school-head"><span class="school-icon">${svg(s.icon)}</span><div><h3>${esc(s.title)}</h3><p class="school-count">${list.length} courses · ${programs.length} program${programs.length === 1 ? '' : 's'}</p></div></div>
            <p>${esc(s.blurb)}</p>
            <details class="school-courses"><summary>See the ${list.length} courses</summary>
              <ul>${list.map((c) => `<li><a href="${c.program_page}#courses">${esc(c.title)}</a><span class="mode-badge mode-${c.delivery_mode}${c.delivery_confirmed ? '' : ' proposed'}">${MODES[c.delivery_mode].label}</span></li>`).join('')}</ul>
            </details>
            <p class="school-programs">${programs.map((p) => `<a href="${p.file}">${esc(plain(p.short))}</a>`).join(' · ')}</p>
          </article>`;
  }).join('');
  return `<!-- schools:start (generated by npm run catalogue) -->
    <section class="section bg-white" id="schools">
      <div class="wrap">
        <div class="section-head reveal">
          <span class="eyebrow">Four schools</span>
          <h2>Browse by school</h2>
          <p class="lead">Every course belongs to one of four schools. Open a school to see its courses and how each one is planned to be taught.</p>
        </div>
        <div class="school-grid">${cards}
        </div>
        <p class="mode-legend"><span class="mode-badge mode-on-campus">On campus</span> <span class="mode-badge mode-blended">Blended</span> <span class="mode-badge mode-online">Online</span> Planned delivery. Except for Special Education (already blended), these are proposals TIME will confirm before each intake. <a href="online-learning.html#modes">How each mode works</a>.</p>
      </div>
    </section>
    <!-- schools:end -->`;
}

export function courseOptions(cat) {
  return `<!-- courses:start (generated by npm run catalogue) -->${SCHOOLS.map((s) => `<optgroup label="${esc(s.short)}">${cat.courses.filter((c) => c.school_id === s.id && c.program_id !== 'special-education').map((c) => `<option>${esc(c.title)}</option>`).join('')}</optgroup>`).join('')}<!-- courses:end -->`;
}

const replaceBetween = (html, start, end, block) => {
  const a = html.indexOf(start), b = html.indexOf(end);
  if (a < 0 || b < 0) throw new Error(`markers ${start} … ${end} not found`);
  return html.slice(0, a) + block + html.slice(b + end.length);
};

export function build() {
  const cat = catalogue();
  const json = JSON.stringify(cat, null, 2) + '\n';
  const programs = replaceBetween(readFileSync(join(ROOT, 'programs.html'), 'utf8'), '<!-- schools:start', '<!-- schools:end -->', schoolsSection(cat));
  const admissions = replaceBetween(readFileSync(join(ROOT, 'admissions.html'), 'utf8'), '<!-- courses:start', '<!-- courses:end -->', courseOptions(cat));
  return { 'data/catalogue.json': json, 'programs.html': programs, 'admissions.html': admissions };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = build();
  const read = (f) => { try { return readFileSync(join(ROOT, f), 'utf8'); } catch { return ''; } };
  const stale = Object.entries(out).filter(([f, text]) => read(f) !== text).map(([f]) => f);
  if (process.argv.includes('--check')) { if (stale.length) { console.error(`Out of date: ${stale.join(', ')}. Run: npm run catalogue`); process.exit(1); } console.log('Catalogue is up to date.'); }
  else { for (const f of stale) writeFileSync(join(ROOT, f), out[f]); console.log(stale.length ? `Updated: ${stale.join(', ')}` : 'Catalogue already up to date.'); }
}
